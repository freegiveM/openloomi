#!/usr/bin/env bash
# Find the WSL-visible Windows host IP and check whether OpenLoomi is reachable
# from inside WSL. Run inside WSL:
#   bash /mnt/d/openloomi3/openloomi/benchmark/continual-learning-bench/scripts/check-openloomi-port.sh

set -u

echo "==== 1: WSL sees Windows host IP ===="
HOST_IP=$(awk '/^nameserver/{print $2; exit}' /etc/resolv.conf 2>/dev/null || echo "unknown")
echo "HOST_IP=$HOST_IP"
echo ""

echo "==== 2: probe common OpenLoomi ports ===="
for port in 3515 8000 8080 3000; do
    if curl -sS --max-time 3 -o /dev/null -w "%{http_code}" "http://${HOST_IP}:${port}/" 2>/dev/null | grep -qE '^[1-5][0-9][0-9]$'; then
        echo "  port ${port}: REACHABLE"
    else
        echo "  port ${port}: not reachable"
    fi
done
echo ""

echo "==== 3: if you know the exact port, set OPENLOOMI_BASE_URL to ===="
echo "    http://${HOST_IP}:<port>"
echo ""

echo "==== 4: write a suggested .env to D:\\clbench-work\\continual-learning-bench\\.env ===="
ENV_FILE="/mnt/d/clbench-work/continual-learning-bench/.env"
if [ -f "$ENV_FILE" ]; then
    echo "$ENV_FILE already exists; not overwriting"
else
    cat > "$ENV_FILE" <<EOF
# Generated by check-openloomi-port.sh
# WSL sees Windows host IP = ${HOST_IP}
OPENLOOMI_BASE_URL=http://${HOST_IP}:3515
OPENLOOMI_TOKEN_PATH=/mnt/d/clbench-work/openloomi.token
OPENLOOMI_AGENT=default

# If 3515 not right, edit OPENLOOMI_BASE_URL above
EOF
    echo "wrote $ENV_FILE (edit OPENLOOMI_BASE_URL if 3515 is wrong)"
    cat "$ENV_FILE"
fi
echo ""

echo "==== 5: reminder: put your auth token in ===="
echo "  D:\\clbench-work\\openloomi.token"
echo "  (one line, no trailing newline)"
